/**
 * Builds the inline MCP App bundle for mobilita_roma_bus_live (MapLibre + ext-apps).
 */
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";
import { MOBILITA_ROMA_MCP_APP_TILE_ORIGIN } from "../../src/lib/mcp/mobilita-roma-mcp-app.constants.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const entry = join(root, "scripts/mcp/mobilita-roma-mcp-app.entry.mjs");
const mapCssPath = join(root, "node_modules/maplibre-gl/dist/maplibre-gl.css");
const workerPath = join(root, "node_modules/maplibre-gl/dist/maplibre-gl-worker.mjs");
const outPath = join(root, "src/lib/mcp/generated/mobilita-roma-mcp-app.payload.ts");

const workerSource = readFileSync(workerPath, "utf8");
const mapCss = readFileSync(mapCssPath, "utf8");

const bundle = await esbuild.build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  write: false,
  minify: true,
  legalComments: "none",
  define: {
    __MAPLIBRE_WORKER__: JSON.stringify(workerSource),
  },
  // ext-apps and maplibre-gl resolve from node_modules.
  mainFields: ["browser", "module", "main"],
});

const script = bundle.outputFiles[0].text;

const cspConnect = [MOBILITA_ROMA_MCP_APP_TILE_ORIGIN];
// MapLibre loads its worker from an inline blob URL (same bundle, no CDN).
const cspResources = ["blob:", MOBILITA_ROMA_MCP_APP_TILE_ORIGIN];

const html = `<!DOCTYPE html>
<html lang="it">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; base-uri 'none'; script-src 'unsafe-inline' blob:; worker-src blob:; style-src 'unsafe-inline'; connect-src ${MOBILITA_ROMA_MCP_APP_TILE_ORIGIN}; img-src ${MOBILITA_ROMA_MCP_APP_TILE_ORIGIN} data: blob:;" />
  <title>Bus Roma live</title>
  <style>
${mapCss}
html, body { margin: 0; height: 100%; font-family: system-ui, sans-serif; }
#map { position: absolute; inset: 0; }
  </style>
</head>
<body>
  <div id="map"></div>
  <script>
${script}
  </script>
</body>
</html>`;

function tsStringLiteral(value) {
  return JSON.stringify(value);
}

const source = `// Generated by scripts/ci/build-mcp-mobilita-app.mjs — do not edit.
// impeccable-disable-file layout-transition: vendored MapLibre CSS embedded in MCP App HTML.
export const MOBILITA_ROMA_MCP_APP_CSP = {
  connectDomains: ${JSON.stringify(cspConnect)} as const,
  resourceDomains: ${JSON.stringify(cspResources)} as const,
} as const;

const html = ${tsStringLiteral(html)};

export function mobilitaRomaBusLiveAppHtml(): string {
  return html;
}
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source);
assert.ok(script.length > 50_000, "bundle unexpectedly small");
assert.ok(html.includes("Map"), "bundle must include map bootstrap");
console.log(`Wrote ${outPath} (${Buffer.byteLength(html, "utf8")} byte HTML)`);
